"""Writes lib/src/builders/ui_dom_icon_paths.g.dart: the SVG path of each
icon name of the A2UI basic catalog, in a 24 by 24 box, converted from the
glyphs of the Material Icons font that ships with Flutter (by Google, CC
BY 4.0), so jackdaw_dom draws the same icons as jackdaw_flutter.

Usage: python3 tool/generate_icon_paths.py /path/to/flutter
Needs fontTools.
"""
import os
import re
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

flutter = sys.argv[1]
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names_file = os.path.join(here, '..', 'jackdaw_flutter', 'lib', 'src', 'ui', 'builders', 'ui_icon_names.dart')
icons_file = os.path.join(flutter, 'packages', 'flutter', 'lib', 'src', 'material', 'icons.dart')
font_file = os.path.join(flutter, 'bin', 'cache', 'artifacts', 'material_fonts', 'MaterialIcons-Regular.otf')

names = re.findall(r"'([a-zA-Z]+)': Icons\.([a-z_0-9]+)", open(names_file).read())
codes = dict(re.findall(r'static const IconData ([a-z_0-9]+) = IconData\(\s*0x([0-9a-f]+)', open(icons_file).read()))
font = TTFont(font_file)
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
em = font['head'].unitsPerEm
scale = 24 / em


def number(value):
    text = f'{value:.2f}'.rstrip('0').rstrip('.')
    return '0' if text == '-0' else text


lines = []
for name, constant in names:
    pen = SVGPathPen(glyphs, ntos=number)
    glyphs[cmap[int(codes[constant], 16)]].draw(
        TransformPen(pen, (scale, 0, 0, -scale, 0, em * scale)))
    lines.append(f"  '{name}': '{pen.getCommands()}',")

out = os.path.join(here, 'lib', 'src', 'builders', 'ui_dom_icon_paths.g.dart')
with open(out, 'w') as f:
    f.write('// GENERATED by tool/generate_icon_paths.py. Do not edit. The paths are\n')
    f.write('// the glyphs of the Material Icons font that ships with Flutter, by\n')
    f.write('// Google, licensed under CC BY 4.0 (LICENSES/), converted to SVG paths.\n')
    f.write('// ignore_for_file: lines_longer_than_80_chars\n\n')
    f.write('/// The SVG path of each icon name of the A2UI basic catalog, in a 24\n')
    f.write('/// by 24 box.\n')
    f.write('const Map<String, String> uiDomIconPaths = {\n')
    f.write('\n'.join(lines) + '\n};\n')
print(f'{len(lines)} icons')
